/**
 * 文書配列を「チャンク」に変換する。各チャンクが検索・出典の最小単位。
 * @returns {Array<{ id, docId, docTitle, section, text }>}
 */
export function toChunks(documents = SAMPLE_DOCUMENTS) {
  const chunks = [];
  for (const doc of documents) {
    for (const sec of doc.sections) {
      chunks.push({
        id: `${doc.id}::${sec.no}`,
        docId: doc.id,
        docTitle: doc.title,
        section: `${sec.no} ${sec.heading}`,
        text: sec.text,
      });
    }
  }
  return chunks;
}
